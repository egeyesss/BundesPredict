@pytest.fixture(scope="module")
def adopted(scratch: ScratchDatabases) -> str:
    name = scratch.create("adopted")
    scratch.alembic_upgrade(name)
    for statement in SEED_ROWS:
        scratch.psql(name, statement)
    scratch.migrate(name, "--fake-initial")
    # A second run proves the adoption is safe to repeat.
    scratch.migrate(name, "--fake-initial")
    return name


def test_adopting_an_alembic_database_ends_on_the_fresh_django_schema(
    scratch: ScratchDatabases, adopted: str, django_schema: Dump
) -> None:
    assert_same_schema(django_schema, normalise_dump(scratch.dump(adopted)))


def test_adoption_keeps_rows_and_converts_timestamps_to_the_same_utc_instant(
    scratch: ScratchDatabases, adopted: str
) -> None:
    def utc(table: str, column: str) -> str:
        return scratch.psql(
            adopted,
            f"SELECT to_char({column} AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') FROM {table}",
        )

    assert scratch.psql(adopted, "SELECT count(*) FROM teams") == "2"
    assert utc("fixtures", "kickoff_utc") == "2026-08-28 18:30:00"
    assert utc("model_runs", "trained_at") == "2026-10-01 03:00:00"
    assert utc("predictions", "created_at") == "2026-10-02 09:15:30"
    assert (
        scratch.psql(adopted, "SELECT adjustments_json->0->>'factor' FROM predictions") == "injury"
    )


def test_adoption_fills_codes_only_for_clubs_present(
    scratch: ScratchDatabases, adopted: str
) -> None:
    rows = scratch.psql(adopted, "SELECT name, code, short_name FROM teams ORDER BY id")

    assert rows.splitlines() == ["Bayern Munich|FCB|Bayern", "Holstein Kiel||"]
