"""The Django models have to describe the tables Alembic created, exactly.

Production was built by Alembic, so Django adopts it with ``migrate --fake-initial``. That only
works if the initial migrations describe the live schema, and a fresh ``migrate`` has to land on
the same schema as an adopted database. Both are checked by diffing ``pg_dump --schema-only``
output from real Postgres 17 containers (the dump runs inside the container so its major version
matches the server).

Normalisation rules applied before comparing (everything else must match character for
character, including defaults, nullability, index names and constraint names):

1. Only the nine football tables are compared; ``alembic_version`` and Django's own tables are
   dropped.
2. Comments, ``SET`` lines, ``\\restrict`` tokens and whitespace layout are ignored.
3. Column order is ignored. Each column is compared as one "table.column: definition" fact.
4. ``serial`` (sequence plus ``nextval`` default, Alembic) and ``GENERATED BY DEFAULT AS
   IDENTITY`` (Django) both reduce to "auto-generated key"; sequence parameters are not compared.
5. Foreign keys are compared by columns, referenced column and ``ON DELETE`` action. Their
   constraint names are ignored because Django derives them from a hash, and
   ``DEFERRABLE INITIALLY DEFERRED``, which Django adds to every foreign key, is dropped.

Expected divergences once every migration has run, declared in ``EXPECTED_DIVERGENCES`` below and
asserted to apply, so they cannot go stale silently: five naive timestamp columns become
``timestamptz``, ``teams`` gains ``code`` and ``short_name``, and ``predictions`` gains its owner,
conversation, token, cost and response columns.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest
from testcontainers.community.postgres import PostgresContainer

REPO_ROOT = Path(__file__).resolve().parents[4]
MANAGE_PY = REPO_ROOT / "apps" / "backend" / "manage.py"

PARITY_TABLES = frozenset(
    {
        "teams",
        "team_aliases",
        "matches",
        "fixtures",
        "players",
        "squad_values",
        "model_runs",
        "team_params",
        "predictions",
    }
)

NAIVE_TIMESTAMP_COLUMNS = frozenset(
    {
        "fixtures.kickoff_utc",
        "model_runs.trained_at",
        "players.scraped_at",
        "predictions.created_at",
        "squad_values.scraped_at",
    }
)

EXPECTED_NEW_FACTS = frozenset(
    {
        "teams.code: character varying(3)",
        "teams.short_name: character varying(20)",
        "teams UNIQUE teams_code_key (code)",
        "predictions.user_id: integer",
        "predictions.conversation_id: uuid",
        "predictions.input_tokens: integer",
        "predictions.output_tokens: integer",
        "predictions.cost_usd: numeric(10,6)",
        "predictions.response_json: jsonb",
        "predictions.CONSTRAINT: predictions_input_tokens_check CHECK ((input_tokens >= 0))",
        "predictions.CONSTRAINT: predictions_output_tokens_check CHECK ((output_tokens >= 0))",
        "predictions FK (user_id) -> auth_user(id) ON DELETE NO ACTION",
        "predictions FK (conversation_id) -> chat_conversation(id) ON DELETE NO ACTION",
        "predictions INDEX predictions_user_id_0719d7ef btree (user_id)",
        "predictions INDEX predictions_conversation_id_deb81265 btree (conversation_id)",
    }
)

Dump = frozenset[str]


def _run(command: list[str], env: dict[str, str]) -> None:
    result = subprocess.run(
        command, cwd=REPO_ROOT, env=env, capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, f"{' '.join(command)}\n{result.stdout}\n{result.stderr}"


class ScratchDatabases:
    """Creates throwaway databases inside the shared Postgres container."""

    def __init__(self, container: PostgresContainer) -> None:
        self.container = container
        self.created = 0

    def create(self, label: str) -> str:
        self.created += 1
        name = f"{label}_{self.created}"
        self.psql("postgres", f"CREATE DATABASE {name}")
        return name

    def url(self, name: str) -> str:
        host = self.container.get_container_host_ip()
        port = self.container.get_exposed_port(5432)
        user, password = self.container.username, self.container.password
        return f"postgresql://{user}:{password}@{host}:{port}/{name}"

    def psql(self, database: str, sql: str) -> str:
        result = self.container.exec(
            [
                "psql",
                "-U",
                self.container.username,
                "-d",
                database,
                "-At",
                "-v",
                "ON_ERROR_STOP=1",
                "-c",
                sql,
            ]
        )
        output = result.output.decode()
        assert result.exit_code == 0, output
        return output.strip()

    def alembic_upgrade(self, name: str) -> None:
        env = {**os.environ, "DATABASE_URL": self.url(name)}
        _run([sys.executable, "-m", "alembic", "upgrade", "head"], env)

    def migrate(self, name: str, *args: str) -> None:
        env = {
            **os.environ,
            "DJANGO_SETTINGS_MODULE": "config.settings.dev",
            "DATABASE_URL": self.url(name),
        }
        _run([sys.executable, str(MANAGE_PY), "migrate", *args], env)

    def dump(self, name: str) -> str:
        result = self.container.exec(
            [
                "pg_dump",
                "--schema-only",
                "--no-owner",
                "--no-privileges",
                "-U",
                self.container.username,
                "-d",
                name,
            ]
        )
        output = result.output.decode()
        assert result.exit_code == 0, output
        return output


def _statements(dump: str) -> list[str]:
    lines = [
        line
        for line in dump.splitlines()
        if line.strip() and not line.startswith("--") and not line.startswith("\\")
    ]
    return [" ".join(chunk.split()) for chunk in "\n".join(lines).split(";\n") if chunk.strip()]


def _strip_schema(text: str) -> str:
    return text.replace("public.", "").replace('"position"', "position")


def normalise_dump(dump: str) -> Dump:
    facts: set[str] = set()
    for statement in _statements(dump):
        statement = _strip_schema(statement.rstrip(";"))

        if match := re.match(r"CREATE TABLE (\w+) \((.*)\)$", statement):
            table, body = match.groups()
            if table not in PARITY_TABLES:
                continue
            for column in re.split(r", (?=\w+ )", body.strip()):
                name, _, definition = column.strip().partition(" ")
                facts.add(f"{table}.{name}: {definition}")
        elif match := re.match(r"CREATE SEQUENCE (\w+)_id_seq ", statement):
            if match.group(1) in PARITY_TABLES:
                facts.add(f"{match.group(1)}.id: auto-generated key")
        elif match := re.match(
            r"ALTER TABLE (?:ONLY )?(\w+) ALTER COLUMN id ADD GENERATED", statement
        ):
            if match.group(1) in PARITY_TABLES:
                facts.add(f"{match.group(1)}.id: auto-generated key")
        elif re.match(r"ALTER (TABLE|SEQUENCE) .*(OWNED BY|SET DEFAULT nextval)", statement):
            continue
        elif match := re.match(
            r"ALTER TABLE (?:ONLY )?(\w+) ADD CONSTRAINT (\w+) FOREIGN KEY \((.*?)\) "
            r"REFERENCES (\w+)\((\w+)\)(?: ON DELETE (CASCADE))?",
            statement,
        ):
            table, _, column, target, target_column, on_delete = match.groups()
            if table in PARITY_TABLES:
                action = on_delete or "NO ACTION"
                facts.add(f"{table} FK ({column}) -> {target}({target_column}) ON DELETE {action}")
        elif match := re.match(
            r"ALTER TABLE (?:ONLY )?(\w+) ADD CONSTRAINT (\w+) (PRIMARY KEY|UNIQUE) \((.*)\)$",
            statement,
        ):
            table, constraint, kind, columns = match.groups()
            if table in PARITY_TABLES:
                facts.add(f"{table} {kind} {constraint} ({columns})")
        elif match := re.match(r"CREATE (UNIQUE )?INDEX (\w+) ON (\w+) USING (.*)$", statement):
            unique, index, table, rest = match.groups()
            if table in PARITY_TABLES:
                facts.add(f"{table} {'UNIQUE ' if unique else ''}INDEX {index} {rest}")
    return frozenset(facts)


def apply_expected_divergences(alembic_facts: Dump) -> Dump:
    """Rewrite the Alembic facts into what the schema looks like after every Django migration."""
    facts = set(alembic_facts)
    for column in NAIVE_TIMESTAMP_COLUMNS:
        table, name = column.split(".")
        naive = next(
            (fact for fact in facts if fact.startswith(f"{column}: timestamp without time zone")),
            None,
        )
        assert naive is not None, f"{column} is no longer a naive timestamp in the Alembic schema"
        facts.remove(naive)
        facts.add(naive.replace("timestamp without time zone", "timestamp with time zone"))
    assert not {fact for fact in facts if "timestamp without time zone" in fact}, (
        "a naive timestamp column is missing from NAIVE_TIMESTAMP_COLUMNS"
    )
    return frozenset(facts | EXPECTED_NEW_FACTS)


def assert_same_schema(expected: Dump, actual: Dump) -> None:
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    assert not missing and not unexpected, (
        "Schemas differ.\nOnly in the Alembic schema:\n  "
        + "\n  ".join(missing)
        + "\nOnly in the Django schema:\n  "
        + "\n  ".join(unexpected)
    )


@pytest.fixture(scope="module")
def scratch(postgres_container: PostgresContainer) -> ScratchDatabases:
    return ScratchDatabases(postgres_container)


@pytest.fixture(scope="module")
def alembic_schema(scratch: ScratchDatabases) -> Dump:
    name = scratch.create("alembic_head")
    scratch.alembic_upgrade(name)
    return normalise_dump(scratch.dump(name))


@pytest.fixture(scope="module")
def django_schema(scratch: ScratchDatabases) -> Dump:
    name = scratch.create("django_full")
    scratch.migrate(name)
    return normalise_dump(scratch.dump(name))


def test_initial_migrations_describe_the_alembic_schema_exactly(
    scratch: ScratchDatabases, alembic_schema: Dump
) -> None:
    name = scratch.create("django_initial")
    scratch.migrate(name, "football", "0001")
    scratch.migrate(name, "predictions", "0001")

    assert_same_schema(alembic_schema, normalise_dump(scratch.dump(name)))


def test_reversing_every_migration_returns_to_the_alembic_schema(
    scratch: ScratchDatabases, alembic_schema: Dump
) -> None:
    name = scratch.create("django_reversed")
    scratch.migrate(name)
    scratch.migrate(name, "predictions", "0001")
    scratch.migrate(name, "football", "0001")

    assert_same_schema(alembic_schema, normalise_dump(scratch.dump(name)))


def test_full_migrate_matches_alembic_apart_from_declared_divergences(
    alembic_schema: Dump, django_schema: Dump
) -> None:
    assert_same_schema(apply_expected_divergences(alembic_schema), django_schema)


